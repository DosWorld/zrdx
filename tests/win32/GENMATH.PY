def bits(x):
    lo, hi = struct.unpack("<II", struct.pack("<d", x))
    return lo, hi


def row(name, a, b, r):
    tol = 0 if name in EXACT else 2
    if name in ("sinh", "cosh", "tanh"):
        tol = 4
    if name == "pow" and a == 1.0001:
        tol = 8
    al, ah = bits(a)
    bl, bh = bits(float(b))
    if name == "ldexp":
        bl, bh = b & 0xFFFFFFFF, 0
    rl, rh = bits(r)
    return ("    {%d, 0x%08XUL, 0x%08XUL, 0x%08XUL, 0x%08XUL,\n"
            "     0x%08XUL, 0x%08XUL, %d},\n") % (
        FN.index(name), al, ah, bl, bh, rl, rh, tol)


