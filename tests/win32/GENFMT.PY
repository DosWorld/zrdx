"""Writes TFMT.C: printf cases checked against Python's own
C-style formatting (correctly rounded). Exponents get three
digits as in the Microsoft runtime.
Usage: python3 GENFMT.PY > TFMT.C
"""
import re
import struct
import sys

WIDTH = 65


def bits(x):
    return struct.unpack("<II", struct.pack("<d", x))


def ms(s):
    return re.sub(r"([eE][+-])(\d{1,2})(?!\d)",
                  lambda m: m.group(1) + m.group(2).zfill(3), s)


def lit(s, indent):
    """C string literal, long text split into adjacent literals.
    """
    esc = s.replace("\\", "\\\\").replace('"', '\\"')
    room = max(WIDTH - indent - 4, 20)
    parts = [esc[i:i + room] for i in range(0, len(esc),
        room)] or [""]
    return ('"\n' + " " * indent + '"').join(parts).join(['"',
        '"'])


INTS = [
    ("%d", -42), ("%i", 42), ("%5d", 7), ("%-5d|", 7),
        ("%05d", -7),
    ("%+d", 5), ("% d", 5), ("%.3d", 5), ("%5.3d", 5),
        ("%x", 255),
    ("%X", 48879), ("%#x", 255), ("%#X", 255), ("%o", 8),
        ("%#o", 8),
    ("%.0d", 0), ("%d", 0), ("%x", 0), ("%#x", 0), ("%08.3d", 5),
    ("%+05d", 42), ("%-08d|", 42), ("%ld", -2000000000),
]
STRS = [("%s", "abc"), ("%.2s", "abc"), ("%6s", "abc"),
        ("%-6s|", "abc"), ("%6.2s", "abc"), ("%s", ""),
        ("[%s]", "x y")]
DBLS = [0.0, 0.5, 1.5, 2.5, 0.1, 123.456, 1e15, 1e22, 1e100,
        1e-5,
        0.0001234, 1.7976931348623157e308, 5e-324,
        3.14159265358979,
        9.9999995, 123456.7]
DFMTS = ["%f", "%e", "%g", "%.0f", "%.1f", "%.10f", "%.20f",
         "%.3e",
         "%.15g", "%.17g", "%10.2f|", "%#g"]


TAIL = r'''/* floating point run-time support */
int fltused_;
char _8087 = 3;

static void say(const char *s)
{
    unsigned long n = 0, w;

    while (s[n])
        n++;
    WriteFile(GetStdHandle(0xFFFFFFF5UL), s, n, &w, 0);
}

static double dbl(unsigned long lo, unsigned long hi)
{
    unsigned long w[2];

    w[0] = lo;
    w[1] = hi;
    return *(double *)w;
}

static int same(const char *a, const char *b)
{
    while (*a && *a == *b)
    {
        a++;
        b++;
    }
    return *a == *b;
}

static int bad;
static char buf[2200];

static void num(int n)
{
    char t[8];

    t[0] = (char)('0' + (n / 1000) % 10);
    t[1] = (char)('0' + (n / 100) % 10);
    t[2] = (char)('0' + (n / 10) % 10);
    t[3] = (char)('0' + n % 10);
    t[4] = ' ';
    t[5] = 0;
    say(t);
}

static void check(int n, const char *got, const char *want)
{
    if (same(got, want))
        return;
    say("\r\nFMT: fail ");
    num(n);
    say(got);
    say("|");
    say(want);
    bad = 1;
}

static void run_cases(void)
{
    int n = 0, i;

    for (i = 0; icases[i].fmt; i++)
    {
        sprintf(buf, icases[i].fmt, icases[i].v);
        check(++n, buf, icases[i].want);
    }
    for (i = 0; dcases[i].fmt; i++)
    {
        sprintf(buf, dcases[i].fmt,
                dbl(dcases[i].lo, dcases[i].hi));
        check(++n, buf, dcases[i].want);
    }
    sprintf(buf, "%c%5c|%-5c|", 65, 66, 67);
    check(++n, buf, "A    B|C    |");
    sprintf(buf, "%u %lu", 4000000000UL, 3000000000UL);
    check(++n, buf, "4000000000 3000000000");
    sprintf(buf, "%I64d %I64u", 0xFFFFFFFFUL, 0xFFFFFFFFUL,
            1UL, 0UL);
    check(++n, buf, "-1 1");
    sprintf(buf, "%I64x", 0x89ABCDEFUL, 0x01234567UL);
    check(++n, buf, "123456789abcdef");
    sprintf(buf, "%I64d", 0UL, 0x80000000UL);
    check(++n, buf, "-9223372036854775808");
    sprintf(buf, "%I64u", 0xFFFFFFFFUL, 0xFFFFFFFFUL);
    check(++n, buf, "18446744073709551615");
    sprintf(buf, "%hd %hu", 70000, 70000);
    check(++n, buf, "4464 4464");
    sprintf(buf, "%*d|%-*d|%.*f", 5, 42, 5, 42, 2,
            dbl(0x66666666UL, 0x40026666UL));
    check(++n, buf, "   42|42   |2.30");
    sprintf(buf, "%p %%|%n", (void *)0xBEEF, (int *)&i);
    check(++n, buf, "0000BEEF %|");
    sprintf(buf, "%f %e %g", dbl(0, 0x7FF00000UL),
            dbl(0, 0xFFF00000UL), dbl(1, 0x7FF80000UL));
    check(++n, buf, "1.#INF -1.#INF 1.#QNAN");
    sprintf(buf, "%S %ls|%5.2S|", L"wide", L"w2", L"abc");
    check(++n, buf, "wide w2|   ab|");
    check(++n, buf, buf);
    i = _snprintf(buf, 5, "abcdefgh");
    check(++n, i == -1 ? "ok" : "no", "ok");
    i = _snprintf(buf, 8, "abcdefgh");
    check(++n, i == 8 ? "ok" : "no", "ok");
    i = _snprintf(buf, 9, "abcdefgh");
    check(++n, i == 8 && buf[8] == 0 ? "ok" : "no", "ok");
}

void mainCRTStartup(void)
{
    run_cases();
    say(bad ? "\r\nFMT: failed\r\n" : "\r\nFMT: ok\r\n");
    exit(bad);
}
'''


def main():
    w = sys.stdout.write
    w("/* Generated by GENFMT.PY - do not edit. */\n")
    w("extern int __cdecl sprintf(char *, const char *, ...);\n")
    w("extern int __cdecl _snprintf(char *, unsigned, const "
      "char *,\n")
    w("                             ...);\n")
    w("extern void __cdecl exit(int);\n")
    w("extern int __stdcall WriteFile(void *, const void *,\n")
    w("                               unsigned long, unsigned "
      "long *,\n")
    w("                               void *);\n")
    w("extern void *__stdcall GetStdHandle(unsigned long);\n\n")
    w("typedef struct DCase\n{\n    const char *fmt;\n")
    w("    unsigned long lo, hi;\n    const char *want;\n} "
      "DCase;\n\n")
    w("typedef struct ICase\n{\n    const char *fmt;\n    long "
      "v;\n")
    w("    const char *want;\n} ICase;\n\n")
    w("static const ICase icases[] =\n{\n")
    cdiff = {"%#o": "010", "%.0d": "", "%#x": "0",
             "%08.3d": "     005"}
    for f, v in INTS:
        want = f % v
        if f in cdiff and (f != "%#x" or v == 0) and (f
            != "%#o" or v == 8):
            want = cdiff[f]
        w("    {%s, %dL, %s},\n" % (lit(f, 8), v, lit(want, 8)))
    w("    {0, 0, 0}\n};\n\n")
    w("static const DCase dcases[] =\n{\n")
    n = 0
    for x in DBLS:
        for f in DFMTS:
            for sign in (1, -1):
                if sign < 0 and (x == 0.0 or f not in ("%f",
                    "%e", "%g")):
                    continue
                v = x * sign
                want = ms(f % v)
                if len(want) > 400:
                    continue
                lo, hi = bits(v)
                w("    {%s,\n     0x%08XUL, 0x%08XUL,\n     "
                  "%s},\n"
                  % (lit(f, 8), lo, hi, lit(want, 5)))
                n += 1
    w("    {0, 0, 0, 0}\n};\n\n")
    sys.stderr.write("%d double cases\n" % n)
    w(TAIL)


main()
